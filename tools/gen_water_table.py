#!/usr/bin/env python3
"""Generate src/water_table.js from IAPWS-95 (pip install iapws).
Single-phase table on a (P, T) grid covering the hot-water heater, mixer and
SCW reactor, plus a saturation table for the flash / recovery train."""
import json, math, sys
from iapws import IAPWS95

P_LIST = [22.5, 23.0, 24.0, 25.0, 26.0, 27.0, 28.0, 30.0]            # MPa
T_LIST = list(range(10, 340, 10)) + list(range(340, 460, 2)) + list(range(460, 701, 10))  # degC
PSAT = [round(10 ** (math.log10(0.02) + i * (math.log10(6.0) - math.log10(0.02)) / 47), 5) for i in range(48)]

def r(x, n=5):
    return float(f"{x:.{n}g}")

single = {"h": [], "rho": [], "mu": [], "k": []}
for P in P_LIST:
    rows = {k: [] for k in single}
    for T in T_LIST:
        s = IAPWS95(T=T + 273.15, P=P)
        rows["h"].append(r(s.h, 7)); rows["rho"].append(r(s.rho, 6))
        rows["mu"].append(r(s.mu * 1e6, 5)); rows["k"].append(r(s.k, 5))
    for k in single:
        single[k].append(rows[k])

sat = {"P": PSAT, "T": [], "hf": [], "hg": [], "rhof": [], "rhog": [], "muf": [], "kf": []}
for P in PSAT:
    l = IAPWS95(P=P, x=0); v = IAPWS95(P=P, x=1)
    sat["T"].append(r(l.T - 273.15, 6)); sat["hf"].append(r(l.h, 6)); sat["hg"].append(r(v.h, 6))
    sat["rhof"].append(r(l.rho, 5)); sat["rhog"].append(r(v.rho, 5))
    sat["muf"].append(r(l.mu * 1e6, 4)); sat["kf"].append(r(l.k, 4))

out = {"source": "IAPWS-95 via python-iapws", "P": P_LIST, "T": T_LIST, **single, "sat": sat}
js = ("// AUTO-GENERATED by tools/gen_water_table.py (IAPWS-95). Do not edit.\n"
      "// Units: P MPa, T degC, h kJ/kg, rho kg/m3, mu uPa.s, k W/m/K\n"
      "(function(root){var W=" + json.dumps(out, separators=(",", ":")) +
      ";if(typeof module==='object'&&module.exports){module.exports=W;}else{root.WATER_TABLE=W;}})"
      "(typeof self!=='undefined'?self:this);\n")
open(sys.argv[1] if len(sys.argv) > 1 else "src/water_table.js", "w").write(js)
print("points", len(P_LIST) * len(T_LIST), "bytes", len(js))
